test_that("build_plan selects targeted or full builds by strategy and change", {
  # Smart strategy: targeted sections for narrow edits.
  doc_only <- build_plan("smart", "R/hello.R", documentation_only = TRUE)
  expect_identical(doc_only$kind, "sections")
  expect_identical(doc_only$targets, "reference")
  expect_true(doc_only$document)
  expect_false(doc_only$reference_lazy)

  rd_edit <- build_plan("smart", "man/hello.Rd")
  expect_identical(rd_edit$kind, "sections")
  expect_identical(rd_edit$targets, "reference")
  expect_identical(rd_edit$reference_files, "hello.Rd")
  expect_false(rd_edit$document)

  article <- build_plan("smart", "vignettes/articles/guide.Rmd")
  expect_identical(article$kind, "sections")
  expect_identical(article$targets, "articles")
  expect_identical(article$article_names, "articles/guide")
  expect_true(article$articles_lazy)

  tutorial <- build_plan("smart", "vignettes/tutorials/intro.Rmd")
  expect_identical(tutorial$kind, "sections")
  expect_identical(tutorial$targets, "tutorials")

  readme_rmd <- build_plan("smart", "README.Rmd")
  expect_identical(readme_rmd$kind, "sections")
  expect_identical(readme_rmd$targets, "home")
  expect_true(readme_rmd$readme)

  readme_md <- build_plan("smart", "README.md")
  expect_identical(readme_md$kind, "sections")
  expect_identical(readme_md$targets, "home")
  expect_false(readme_md$readme)

  news <- build_plan("smart", "NEWS.md")
  expect_identical(news$kind, "sections")
  expect_identical(news$targets, "news")

  for (path in c(
    "pkgdown/extra.css",
    "pkgdown/assets/app.js",
    "man/figures/logo.png"
  )) {
    asset <- build_plan("smart", path)
    expect_identical(asset$kind, "sections", info = path)
    expect_identical(asset$targets, "assets", info = path)
  }

  # Smart strategy: structural edits, code changes, and deletions trigger full builds.
  for (path in c(
    "R/hello.R",
    "DESCRIPTION",
    "NAMESPACE",
    "_pkgdown.yml",
    "data/example.rda",
    "src/code.c",
    "inst/extdata/file.csv",
    "pkgdown/templates/head.html"
  )) {
    structural <- build_plan("smart", path, documentation_only = FALSE)
    expect_identical(structural$kind, "site", info = path)
    expect_false(structural$lazy, info = path)
  }

  deleted <- build_plan("smart", "vignettes/old.Rmd", deleted = TRUE)
  expect_identical(deleted$kind, "site")
  expect_false(deleted$lazy)

  unclassified <- build_plan("smart", "CITATION")
  expect_identical(unclassified$kind, "site")
  expect_true(unclassified$lazy)

  # Lazy and full strategies + force_full override.
  lazy <- build_plan("lazy", "vignettes/guide.Rmd")
  expect_identical(lazy$kind, "site")
  expect_true(lazy$lazy)

  full <- build_plan("full", "vignettes/guide.Rmd")
  expect_identical(full$kind, "site")
  expect_false(full$lazy)

  forced <- build_plan("lazy", "vignettes/guide.Rmd", force_full = TRUE)
  expect_identical(forced$kind, "site")
  expect_false(forced$lazy)
  expect_true(forced$document)
  expect_true(forced$readme)
})

test_that("startup and manual rebuilds refresh generated inputs in the shadow", {
  skip_if_not(rmarkdown::pandoc_available("2.10.1"))
  root <- make_package()
  mirror <- tempfile("updoc-preprocessing-")
  on.exit(unlink(c(root, mirror), recursive = TRUE), add = TRUE)
  writeLines(
    c(
      "#' Current greeting",
      "#' @return A greeting.",
      "#' @export",
      "hello <- function() 'hello'"
    ),
    file.path(root, "R", "hello.R")
  )
  writeLines(
    c(
      "# Generated by roxygen2: do not edit by hand",
      "export(hello)"
    ),
    file.path(root, "NAMESPACE")
  )
  dir.create(file.path(root, "man"))
  stale_rd <- c(
    "% Generated by roxygen2: do not edit by hand",
    "% Please edit documentation in R/hello.R",
    "\\name{hello}",
    "\\alias{hello}",
    "\\title{Stale greeting}",
    "\\description{Stale greeting}"
  )
  writeLines(stale_rd, file.path(root, "man", "hello.Rd"))
  writeLines(
    c("---", "output: github_document", "---", "", "# Current home"),
    file.path(root, "README.Rmd")
  )
  writeLines("# Stale home", file.path(root, "README.md"))
  mirror_package(root, mirror)
  state <- new_preview_state(root, tempfile(), TRUE, "smart", 4321, 1, TRUE)
  state$build_root <- mirror
  state$worker <- TRUE
  local_mocked_bindings(
    run_pkgdown = function(state, plan) TRUE,
    .package = "updoc"
  )

  expect_true(suppressMessages(execute_build(
    state,
    file.path(root, "<initial>"),
    initial = TRUE
  )))
  expect_match(
    paste(readLines(file.path(mirror, "man", "hello.Rd")), collapse = "\n"),
    "Current greeting",
    fixed = TRUE
  )
  expect_match(
    paste(readLines(file.path(mirror, "README.md")), collapse = "\n"),
    "Current home",
    fixed = TRUE
  )
  expect_identical(readLines(file.path(root, "man", "hello.Rd")), stale_rd)
  expect_identical(readLines(file.path(root, "README.md")), "# Stale home")

  # Rebuilding explicitly must repair stale generated inputs as well.
  writeLines(stale_rd, file.path(mirror, "man", "hello.Rd"))
  writeLines("# Stale home", file.path(mirror, "README.md"))
  expect_true(suppressMessages(execute_build(
    state,
    file.path(root, "<rebuild>"),
    force_full = TRUE
  )))
  expect_match(
    paste(readLines(file.path(mirror, "man", "hello.Rd")), collapse = "\n"),
    "Current greeting",
    fixed = TRUE
  )
  expect_match(
    paste(readLines(file.path(mirror, "README.md")), collapse = "\n"),
    "Current home",
    fixed = TRUE
  )

  # document = FALSE still renders a README, and a missing Rmd is harmless.
  state$document <- FALSE
  writeLines(stale_rd, file.path(mirror, "man", "hello.Rd"))
  writeLines("# Stale home", file.path(mirror, "README.md"))
  expect_true(suppressMessages(execute_build(
    state,
    file.path(root, "<rebuild>"),
    force_full = TRUE
  )))
  expect_identical(readLines(file.path(mirror, "man", "hello.Rd")), stale_rd)
  expect_match(
    paste(readLines(file.path(mirror, "README.md")), collapse = "\n"),
    "Current home",
    fixed = TRUE
  )
  unlink(file.path(root, "README.Rmd"))
  expect_true(suppressMessages(execute_build(
    state,
    file.path(root, "<rebuild>"),
    force_full = TRUE
  )))
  expect_false(file.exists(file.path(mirror, "README.Rmd")))
})

test_that("a forced recovery refreshes inputs skipped by initial validation", {
  root <- make_package()
  mirror <- tempfile("updoc-preprocessing-retry-")
  on.exit(unlink(c(root, mirror), recursive = TRUE), add = TRUE)
  dir.create(file.path(root, "vignettes"))
  article <- file.path(root, "vignettes", "article.Rmd")
  writeLines(c("---", "title: Broken"), article)
  mirror_package(root, mirror)
  state <- new_preview_state(root, tempfile(), TRUE, "smart", 4321, 1, TRUE)
  state$build_root <- mirror
  state$worker <- TRUE
  calls <- character()
  local_mocked_bindings(
    run_documentation = function(state) {
      calls <<- c(calls, "documentation")
      list()
    },
    run_readme = function(state) calls <<- c(calls, "readme"),
    run_pkgdown = function(state, plan) TRUE,
    .package = "updoc"
  )
  expect_false(suppressMessages(execute_build(
    state,
    file.path(root, "<initial>"),
    initial = TRUE
  )))
  expect_length(calls, 0L)
  writeLines(c("---", "title: Repaired", "---", "Content."), article)
  expect_true(suppressMessages(execute_build(
    state,
    article,
    force_full = TRUE
  )))
  expect_identical(calls, c("documentation", "readme"))
})

test_that("shadow prebuilds preserve concurrent source edits in the next queue", {
  root <- make_package()
  mirror <- tempfile("updoc-preprocessing-concurrent-")
  on.exit(unlink(c(root, mirror), recursive = TRUE), add = TRUE)
  dir.create(file.path(root, "man"))
  rd <- file.path(root, "man", "hello.Rd")
  readme <- file.path(root, "README.md")
  writeLines("Old documentation", rd)
  writeLines("Old README", readme)
  mirror_package(root, mirror)
  state <- new_preview_state(root, tempfile(), TRUE, "smart", 4321, 1, TRUE)
  state$build_root <- mirror
  state$worker <- TRUE
  local_mocked_bindings(
    run_documentation = function(state) {
      writeLines("Concurrently edited documentation", rd)
      list()
    },
    run_readme = function(state)
      writeLines("Concurrently edited README", readme),
    run_pkgdown = function(state, plan) TRUE,
    .package = "updoc"
  )
  expect_true(suppressMessages(execute_build(
    state,
    file.path(root, "<initial>"),
    initial = TRUE
  )))
  expect_setequal(state$observed_changes, c(rd, readme))
})

test_that("targeted rebuilds require a complete, error-free published site", {
  root <- make_package()
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  dir.create(file.path(root, "vignettes"))
  article <- file.path(root, "vignettes", "article.Rmd")
  writeLines(c("---", "title: Article", "---", "Content."), article)
  work <- file.path(root, "work")
  published <- file.path(root, "published")
  dir.create(work)
  dir.create(published)
  writeLines("Partial home page", file.path(work, "index.html"))
  dispatched <- NULL
  local_mocked_bindings(
    dispatch_build_job = function(
      state,
      changed,
      force_full,
      initial,
      can_yield = FALSE
    ) {
      dispatched <<- list(force_full = force_full, can_yield = can_yield)
    },
    .package = "updoc"
  )
  state <- new_preview_state(root, work, TRUE, "smart", 4321, 1, TRUE)
  state$build_dir <- work
  state$site_dir <- published
  state$published_site_dir <- published

  # Missing published home page and rebuild_count == 0 force full build.
  suppressMessages(request_rebuild(state, article))
  expect_identical(dispatched, list(force_full = TRUE, can_yield = FALSE))
  state_end_build(state)

  # Warm output alone does not satisfy rebuild_count > 0.
  writeLines("Warm home page", file.path(published, "index.html"))
  suppressMessages(request_rebuild(state, article))
  expect_identical(dispatched, list(force_full = TRUE, can_yield = FALSE))
  state_end_build(state)

  # After a successful build with index.html present, targeted article builds yield.
  state$rebuild_count <- 1L
  suppressMessages(request_rebuild(state, article))
  expect_identical(dispatched, list(force_full = FALSE, can_yield = TRUE))
  state_end_build(state)

  # Any prior build error forces a complete recovery rebuild.
  state$last_error <- list(message = "A structural rebuild failed")
  suppressMessages(request_rebuild(state, article))
  expect_identical(dispatched, list(force_full = TRUE, can_yield = FALSE))
  state_end_build(state)
  state$last_error <- NULL

  # A deleted published home page also forces full recovery.
  unlink(file.path(published, "index.html"))
  suppressMessages(request_rebuild(state, article))
  expect_identical(dispatched, list(force_full = TRUE, can_yield = FALSE))
  state_end_build(state)
})
